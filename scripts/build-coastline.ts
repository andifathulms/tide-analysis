/**
 * Regenerates lib/chart/coastline.ts from Natural Earth land polygons.
 *
 *   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_land.geojson
 *   pnpm atlas:coastline ne_50m_land.geojson
 *
 * Natural Earth is in the public domain (naturalearthdata.com/about/terms-of-use),
 * so it needs no entry behind the licence gate, which governs sea-level
 * records. Dev-time only: the build reads the committed output and never the
 * network.
 *
 * Each ring is projected with the atlas's own projection, vertices far outside
 * the frame are clamped to a margin box (the edges they draw stay off-screen),
 * and vertices closer than MIN_STEP px to the last kept one are dropped. Whole
 * pixels: at 960 across, half a pixel of coastline is not information.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { ATLAS_HEIGHT, ATLAS_WIDTH, project } from '../lib/chart/atlas'

const MARGIN = 24
const MIN_STEP = 2

type Ring = Array<[number, number]>

const source = process.argv[2]
if (source === undefined) {
  console.error('usage: pnpm atlas:coastline <ne_50m_land.geojson>')
  process.exit(1)
}

const geo = JSON.parse(readFileSync(source, 'utf8')) as {
  features: Array<{ geometry: { type: string; coordinates: unknown } }>
}

const rings: Ring[] = []
for (const feature of geo.features) {
  const { type, coordinates } = feature.geometry
  if (type === 'Polygon') rings.push(...(coordinates as Ring[]))
  else if (type === 'MultiPolygon') for (const poly of coordinates as Ring[][]) rings.push(...poly)
}

const clamp = (v: number, lo: number, hi: number) => Math.min(Math.max(v, lo), hi)
const paths: string[] = []

for (const ring of rings) {
  const points = ring.map(([lon, lat]) => project(lon, lat))
  const inside = points.some(
    (p) => p.x >= 0 && p.x <= ATLAS_WIDTH && p.y >= 0 && p.y <= ATLAS_HEIGHT,
  )
  if (!inside) continue

  const kept: Array<{ x: number; y: number }> = []
  for (const point of points) {
    const p = {
      x: clamp(point.x, -MARGIN, ATLAS_WIDTH + MARGIN),
      y: clamp(point.y, -MARGIN, ATLAS_HEIGHT + MARGIN),
    }
    const last = kept[kept.length - 1]
    if (last !== undefined && Math.hypot(p.x - last.x, p.y - last.y) < MIN_STEP) continue
    kept.push(p)
  }
  if (kept.length < 3) continue
  paths.push(
    'M' + kept.map((p) => `${Math.round(p.x)} ${Math.round(p.y)}`).join('L') + 'Z',
  )
}

const out = `/**
 * Generated by scripts/build-coastline.ts from Natural Earth 1:50m land
 * (v5.1.2, public domain). Do not edit by hand; regenerate instead.
 *
 * Projected into the atlas frame (${ATLAS_WIDTH} × ${ATLAS_HEIGHT}) by lib/chart/atlas.
 */
export const COASTLINE_PATH =
  '${paths.join('')}'
`
writeFileSync('lib/chart/coastline.ts', out)
console.log(`${paths.length} rings, ${(out.length / 1024).toFixed(1)} KB`)
